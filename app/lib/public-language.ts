export const publicLanguages = [
  { code: "en", label: "English" },
  { code: "my", label: "မြန်မာ" },
  { code: "ar", label: "Arabic" },
  { code: "fa", label: "Dari" },
  { code: "kar", label: "Karen" },
  { code: "vi", label: "Vietnamese" },
] as const;

export type PublicLanguage = (typeof publicLanguages)[number]["code"];

const STORAGE_KEY = "bcc-public-language";

export function usePublicLanguage() {
  const [language, setLanguage] = useState<PublicLanguage>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored && publicLanguages.some((option) => option.code === stored)) {
      setLanguage(stored as PublicLanguage);
    }
  }, []);

  function changeLanguage(next: PublicLanguage) {
    setLanguage(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }

  return [language, changeLanguage] as const;
}

